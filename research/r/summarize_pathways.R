args<-commandArgs(trailingOnly=TRUE);stopifnot(length(args)==1L)
d<-args[[1]]
c<-read.csv(file.path(d,"camera_all_terms.csv"),stringsAsFactors=FALSE)
o<-read.csv(file.path(d,"ora_deseq2_baseline.csv"),stringsAsFactors=FALSE)
n<-read.csv(file.path(d,"ora_common_universe_no_if.csv"),stringsAsFactors=FALSE)
g<-read.csv(file.path(d,"goseq_sensitivities.csv"),stringsAsFactors=FALSE)
cat("CAMERA by analysis/correlation:\n")
print(aggregate(as.integer(c$fdr<.05)~analysis+correlation,c,sum))
cat("Significant CAMERA full estimated terms:\n")
print(head(c[c$analysis=="full"&c$correlation=="estimated"&c$fdr<.05,],12))
cat("ORA baseline significant:",sum(o$fdr<.05),"/",nrow(o),"; IF-off:",sum(n$fdr<.05),"/",nrow(n),"\n")
for(a in unique(g$analysis))cat("GOseq",a,"over:",sum(g$analysis==a&g$fdr_over<.05),"under:",sum(g$analysis==a&g$fdr_under<.05),"of",sum(g$analysis==a),"; clipped:",sum(g$analysis==a&g$over_p_clipped)+sum(g$analysis==a&g$under_p_clipped),"\n")
cat("GOseq length significant top:\n")
gt<-g[g$analysis=="exon_union_length"&g$fdr_over<.05,];print(head(gt[order(gt$fdr_over),],12))
